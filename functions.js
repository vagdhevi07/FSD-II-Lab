"use strict";
//1. Function (No Parameters, No Return Type)
function sayHello() {
    console.log("Hello!");
}
sayHello();
//2. Function with Parameter
function greet(name) {
    console.log("Hello " + name);
}
greet("Ravi");
//3. Function with Return Type
function add(a, b) {
    return a + b;
}
console.log(add(10, 20));
